#!/usr/bin/env node

import { readFile, mkdir, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import { compileFromFile } from "json-schema-to-typescript";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const outputRoot = join(root, "contracts", "generated", "typescript");
const checkOnly = process.argv.includes("--check");
const contracts = [
  ["contracts/domain/authority.v3.schema.json", "authority.v3.ts"],
  ["contracts/domain/actions.v3.schema.json", "actions.v3.ts"],
  ["contracts/domain/context-packet.v3.schema.json", "context-packet.v3.ts"],
  ["contracts/domain/runtime-state.v1.schema.json", "runtime-state.v1.ts"],
  ["contracts/domain/controller-state.v1.schema.json", "controller-state.v1.ts"],
  ["contracts/domain/async-runtime.v1.schema.json", "async-runtime.v1.ts"],
  ["contracts/domain/runtime-amendment.v1.schema.json", "runtime-amendment.v1.ts"],
  ["contracts/domain/planning.v1.schema.json", "planning.v1.ts"],
  ["contracts/events/journal-entry.v1.schema.json", "journal-entry.v1.ts"],
];
const bannerComment = [
  "/*",
  " * Generated from the versioned WAJE vNext JSON Schema.",
  " * Run `npm run generate:contracts`; do not edit this file directly.",
  " */",
].join("\n");

await mkdir(outputRoot, { recursive: true });

const stale = [];
for (const [schemaPath, outputName] of contracts) {
  const sourcePath = join(root, schemaPath);
  const outputPath = join(outputRoot, outputName);
  const generated = await compileFromFile(sourcePath, {
    bannerComment,
    format: true,
    style: {
      bracketSpacing: true,
      printWidth: 100,
      semi: true,
      singleQuote: false,
      tabWidth: 2,
      trailingComma: "all",
      useTabs: false,
    },
  });

  if (checkOnly) {
    let current = null;
    try {
      current = await readFile(outputPath, "utf8");
    } catch (error) {
      if (error.code !== "ENOENT") {
        throw error;
      }
    }
    if (current !== generated) {
      stale.push(relative(root, outputPath));
    }
    continue;
  }

  await writeFile(outputPath, generated, "utf8");
}

if (stale.length > 0) {
  throw new Error(
    `Generated contract bindings are stale or missing:\n${stale
      .map((path) => `- ${path}`)
      .join("\n")}`,
  );
}
